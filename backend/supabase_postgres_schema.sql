create table if not exists public.users (
  user_id integer generated by default as identity primary key,
  full_name varchar(255) not null,
  first_name varchar(100),
  last_name varchar(100),
  username varchar(100) not null unique,
  password varchar(255) not null,
  role_id integer not null references public.roles(role_id),
  created_by integer,
  status text not null default 'Activate' check (status in ('Activate', 'Deactivate')),
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  branch_id integer references public.branches(branch_id),
  contact_number varchar(20),
  pin_code varchar(10),
  constraint users_created_by_fkey
    foreign key (created_by) references public.users(user_id) on delete set null
);

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'branches_created_by_fkey'
  ) then
    alter table public.branches
      add constraint branches_created_by_fkey
      foreign key (created_by) references public.users(user_id) on delete set null;
  end if;
end;
$$;

