create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;

create or replace function public.ifnull(a anycompatible, b anycompatible)
returns anycompatible
language sql
immutable
as $$
  select coalesce(a, b)
$$;

create or replace function public.curdate()
returns date
language sql
stable
as $$
  select current_date
$$;

create or replace function public.rand()
returns double precision
language sql
volatile
as $$
  select random()
$$;

create or replace function public.year(value timestamptz)
returns integer
language sql
immutable
as $$
  select extract(year from value)::integer
$$;

create or replace function public.month(value timestamptz)
returns integer
language sql
immutable
as $$
  select extract(month from value)::integer
$$;

create or replace function public.quarter(value timestamptz)
returns integer
language sql
immutable
as $$
  select extract(quarter from value)::integer
$$;

create or replace function public.week(value timestamptz, mode integer default 0)
returns integer
language sql
immutable
as $$
  select case
    when mode = 1 then to_char(value, 'IW')::integer
    else extract(week from value)::integer
  end
$$;

create or replace function public.date_format(value timestamptz, format_text text)
returns text
language sql
immutable
as $$
  select to_char(
    value,
    replace(
      replace(
        replace(
          replace(
            replace(format_text, '%Y', 'YYYY'),
            '%m', 'MM'
          ),
          '%d', 'DD'
        ),
        '%H', 'HH24'
      ),
      '%i', 'MI'
    )
  )
$$;

create or replace function public.convert_tz(value timestamptz, from_tz text, to_tz text)
returns timestamp
language sql
stable
as $$
  select timezone(to_tz, value)
$$;

create or replace function public.timestampdiff(unit_name text, start_value timestamptz, end_value timestamptz)
returns bigint
language sql
immutable
as $$
  select case upper(unit_name)
    when 'MINUTE' then floor(extract(epoch from (end_value - start_value)) / 60)::bigint
    when 'HOUR' then floor(extract(epoch from (end_value - start_value)) / 3600)::bigint
    when 'DAY' then floor(extract(epoch from (end_value - start_value)) / 86400)::bigint
    else floor(extract(epoch from (end_value - start_value)))::bigint
  end
$$;

